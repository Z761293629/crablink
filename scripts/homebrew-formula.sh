#!/bin/sh
# Usage: homebrew-formula.sh X.Y.Z <dir>
# Prints the Homebrew formula for crablink X.Y.Z to stdout. <dir> holds the
# Release's crablink-<target>.tar.gz assets; their sha256 goes into the formula.
# This script is the formula's only source; the tap holds its output (ADR-0004).
set -eu
version="$1"
dir="$2"
base="https://github.com/Z761293629/crablink/releases/download/v$version"

sha() {
  shasum -a 256 "$dir/crablink-$1.tar.gz" | cut -d ' ' -f 1
}

# Fail before printing anything if an asset is missing.
mac_arm=$(sha aarch64-apple-darwin)
linux_intel=$(sha x86_64-unknown-linux-musl)
linux_arm=$(sha aarch64-unknown-linux-musl)

cat <<EOF
# Generated by scripts/homebrew-formula.sh in Z761293629/crablink. Do not edit.
class Crablink < Formula
  desc "用 Rust 写的自托管短链服务：一个 server，一个 CLI，一个 SQLite 文件"
  homepage "https://github.com/Z761293629/crablink"
  # macOS arm64. Intel Macs have no build: they load this url, then fail the arch requirement.
  url "$base/crablink-aarch64-apple-darwin.tar.gz"
  sha256 "$mac_arm"

  on_macos do
    depends_on arch: :arm64
  end

  on_linux do
    on_intel do
      url "$base/crablink-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$linux_intel"
    end
    on_arm do
      url "$base/crablink-aarch64-unknown-linux-musl.tar.gz"
      sha256 "$linux_arm"
    end
  end

  def install
    bin.install "crablink"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/crablink --version")
  end
end
EOF
